def rust_doc(note: Any, indent: str = "", marker: str = "///") -> list[str]:
    return [f"{indent}{marker} {line}" if line else f"{indent}{marker}" for line in as_lines(note)]


def rust_str(value: str | None) -> str:
    if value is None:
        return "None"
    escaped = value.replace("\\", "\\\\").replace('"', '\\"')
    return f'Some("{escaped}")'


def rust_session(session: dict[str, Any], indent: int) -> list[str]:
    pad = " " * indent
    return [
        f"{pad}session: Session {{",
        f'{pad}    authority: "{session["authority"]}",',
        f'{pad}    method: "{session["method"]}",',
        f'{pad}    path: "{session["path"]}",',
        f'{pad}    request_line: "{request_line(session)}",',
        f"{pad}}},",
    ]


def gen_rust(spec: dict[str, Any]) -> str:
    lines = [header("//").rstrip("\n"), ""]
    lines += rust_doc(spec.get("note"), marker="//!")
    lines += [
        "",
        "/// Which shape a platform's immutable identifier takes in its response.",
        "///",
        "/// The bare-integer form takes its structural terminator with it, which is",
        "/// what proves the revealed digits are the whole number rather than a prefix",
        "/// of a longer one (REQ-PLAT-51).",
        "#[derive(Clone, Copy, Debug, PartialEq, Eq)]",
        "pub enum IdShape {",
        "    /// `\"id\":\"2244994945\"`.",
        "    JsonString,",
        "    /// `\"id\":583231,`",
        "    JsonInteger,",
        "}",
        "",
        "/// One notarized session: which server, and which request.",
        "#[derive(Clone, Copy, Debug, PartialEq, Eq)]",
        "pub struct Session {",
        "    /// The lowercase TLS server name the notary authenticates, with no",
        "    /// trailing dot. `authorityId` is its keccak256, which the verifier",
        "    /// compares against the constant its profile pins (REQ-COMMON-21A). It is",
        "    /// also the `Host` header the request carries.",
        "    pub authority: &'static str,",
        "    pub method: &'static str,",
        "    pub path: &'static str,",
        "    /// The request-line prefix the verifier compares byte for byte, trailing",
        "    /// space included. The space is what stops `GET /user ` prefixing",
        "    /// `GET /users/me`.",
        "    pub request_line: &'static str,",
        "}",
        "",
        "/// The token session: the OAuth exchange.",
        "#[derive(Clone, Copy, Debug, PartialEq, Eq)]",
        "pub struct TokenSession {",
        "    pub session: Session,",
        "    /// The body field committed rather than revealed, ordered last so the",
        "    /// committed run is a suffix (REQ-COMMON-22). `None` for a public client,",
        "    /// whose request hides nothing and is revealed whole.",
        "    pub secret_field: Option<&'static str>,",
        "    /// Every header this request sends, lowercased as the wire spells them,",
        "    /// in no particular order. `content-length` is absent because its value",
        "    /// is the body's own count: the HTTP client appends it and the verifier",
        "    /// reads it rather than compares it.",
        "    pub request_headers: &'static [&'static str],",
        "    /// The same lines joined by CRLF, which is the shape a Platform",
        "    /// Verifier splits and matches as a set -- order is the prover's, the",
        "    /// set is the profile's.",
        "    pub request_header_block: &'static str,",
        "}",
        "",
        "/// The identity session: the authenticated read that names the account.",
        "#[derive(Clone, Copy, Debug, PartialEq, Eq)]",
        "pub struct IdentitySession {",
        "    pub session: Session,",
        "    pub id_field: &'static str,",
        "    pub id_shape: IdShape,",
        "    pub handle_field: &'static str,",
        "}",
        "",
        "/// One platform's ceremony profile at one Platform Ceremony Version.",
        "#[derive(Clone, Copy, Debug, PartialEq, Eq)]",
        "pub struct Profile {",
        "    /// The platform name. `platformId` is its keccak256.",
        "    pub platform: &'static str,",
        "    /// A profile is the pair, not the name (REQ-PLAT-01).",
        "    pub ceremony_version: u16,",
        "    /// `None` where the profile notarizes nothing.",
        "    pub token: Option<TokenSession>,",
        "    pub identity: Option<IdentitySession>,",
        "}",
        "",
        "impl Profile {",
        "    /// How many attestations a submission for this profile carries. Derived",
        "    /// from the sessions rather than stated beside them (REQ-COMMON-41).",
        "    pub const fn attestation_count(&self) -> u8 {",
        "        self.token.is_some() as u8 + self.identity.is_some() as u8",
        "    }",
        "}",
        "",
    ]

    for profile in spec["profiles"]:
        name = upper(profile["platform"])
        lines += rust_doc(profile.get("note"))
        lines.append(f"pub const {name}: Profile = Profile {{")
        lines.append(f'    platform: "{profile["platform"]}",')
        lines.append(f"    ceremony_version: {profile['ceremonyVersion']},")

        token = profile["sessions"].get("token")
        if token is None:
            lines.append("    token: None,")
        else:
            headers = ", ".join(f'"{line}"' for line in token["requestHeaders"])
            lines.append("    token: Some(TokenSession {")
            lines += rust_session(token, 8)
            lines.append(f"        secret_field: {rust_str(token['secretField'])},")
            lines.append(f"        request_headers: &[{headers}],")
            lines.append(
                f'        request_header_block: "{escaped(request_header_block(token))}",'
            )
            lines.append("    }),")

        identity = profile["sessions"].get("identity")
        if identity is None:
            lines.append("    identity: None,")
        else:
            shape = "JsonString" if identity["idShape"] == "jsonString" else "JsonInteger"
            lines.append("    identity: Some(IdentitySession {")
            lines += rust_session(identity, 8)
            lines.append(f'        id_field: "{identity["idField"]}",')
            lines.append(f"        id_shape: IdShape::{shape},")
            lines.append(f'        handle_field: "{identity["handleField"]}",')
            lines.append("    }),")
        lines += ["};", ""]

    names = ", ".join(f"&{upper(p['platform'])}" for p in spec["profiles"])
    lines += [
        "/// The closed launch list. A platform outside it has no profile, and",
        "/// `CeremonyProfile.attestationCount` reverts on one.",
        f"pub const LAUNCH: &[&Profile] = &[{names}];",
        "",
        "/// The launch profile for a platform name, or nothing.",
        "///",
        "/// Nothing, rather than a default: a caller that cannot name the platform has",
        "/// nothing to notarize, and guessing produces evidence no verifier accepts.",
        "pub fn launch(platform: &str) -> Option<&'static Profile> {",
        "    LAUNCH.iter().copied().find(|p| p.platform == platform)",
        "}",
        "",
        "/// Governance-owned launch parameters, in seconds.",
        f"pub const MAX_FUTURE_ATTESTATION_SKEW_SECONDS: u64 = "
        f"{spec['parameters']['maxFutureAttestationSkewSeconds']};",
    ]
    for profile in spec["profiles"]:
        if "proofLifetimeSeconds" not in profile:
            continue
        lines.append(
            f"pub const PROOF_LIFETIME_SECONDS_{upper(profile['platform'])}: u64 = "
            f"{profile['proofLifetimeSeconds']};"
        )
    lines.append("")
    return "\n".join(lines)


