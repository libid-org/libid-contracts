def ts_str(value: str | None) -> str:
    if value is None:
        return "null"
    escaped = value.replace("\\", "\\\\").replace("'", "\\'")
    return f"'{escaped}'"


def ts_doc(note: Any, indent: str = "") -> list[str]:
    lines = as_lines(note)
    if not lines:
        return []
    out = [f"{indent}/**"]
    out += [f"{indent} * {line}" if line else f"{indent} *" for line in lines]
    out.append(f"{indent} */")
    return out


def ts_session(session: dict[str, Any], indent: int) -> list[str]:
    pad = " " * indent
    return [
        f"{pad}session: {{",
        f'{pad}  authority: {ts_str(session["authority"])},',
        f'{pad}  method: {ts_str(session["method"])},',
        f'{pad}  path: {ts_str(session["path"])},',
        f"{pad}  requestLine: {ts_str(request_line(session))},",
        f"{pad}}},",
    ]


def gen_ts(spec: dict[str, Any]) -> str:
    lines = [header("//").rstrip("\n"), ""]
    lines += ts_doc(spec.get("note"))
    lines += [
        "",
        "/** Which shape a platform's immutable identifier takes in its response. */",
        "export type IdShape = 'jsonString' | 'jsonInteger'",
        "",
        "export interface Session {",
        "  /** The lowercase TLS server name the notary authenticates. */",
        "  readonly authority: string",
        "  readonly method: string",
        "  readonly path: string",
        "  /** The request-line prefix the verifier compares byte for byte. */",
        "  readonly requestLine: string",
        "}",
        "",
        "export interface TokenSession {",
        "  readonly session: Session",
        "  /** The body field committed rather than revealed, or null. */",
        "  readonly secretField: string | null",
        "  /** Every header this request sends, lowercased, in no particular order.",
        "   * `content-length` is absent: the HTTP client appends it. */",
        "  readonly requestHeaders: readonly string[]",
        "  /** The same lines joined by CRLF, which a Platform Verifier splits and",
        "   * matches as a set. */",
        "  readonly requestHeaderBlock: string",
        "}",
        "",
        "export interface IdentitySession {",
        "  readonly session: Session",
        "  readonly idField: string",
        "  readonly idShape: IdShape",
        "  readonly handleField: string",
        "}",
        "",
        "export interface Profile {",
        "  /** The platform name. The platform id is its keccak256. */",
        "  readonly platform: string",
        "  readonly ceremonyVersion: number",
        "  readonly token: TokenSession | null",
        "  readonly identity: IdentitySession | null",
        "}",
        "",
    ]

    for profile in spec["profiles"]:
        name = upper(profile["platform"])
        lines += ts_doc(profile.get("note"))
        lines.append(f"export const {name}: Profile = {{")
        lines.append(f"  platform: {ts_str(profile['platform'])},")
        lines.append(f"  ceremonyVersion: {profile['ceremonyVersion']},")

        token = profile["sessions"].get("token")
        if token is None:
            lines.append("  token: null,")
        else:
            lines.append("  token: {")
            lines += ts_session(token, 4)
            lines.append(f"    secretField: {ts_str(token['secretField'])},")
            # Broken across lines the way the repository's formatter would
            # break them, so a generated file passes `fmt:check` unformatted.
            lines.append("    requestHeaders: [")
            lines += [f"      {ts_str(line)}," for line in token["requestHeaders"]]
            lines.append("    ],")
            lines.append("    requestHeaderBlock:")
            lines.append(f"      '{escaped(request_header_block(token))}',")
            lines.append("  },")

        identity = profile["sessions"].get("identity")
        if identity is None:
            lines.append("  identity: null,")
        else:
            lines.append("  identity: {")
            lines += ts_session(identity, 4)
            lines.append(f"    idField: {ts_str(identity['idField'])},")
            lines.append(f"    idShape: {ts_str(identity['idShape'])},")
            lines.append(f"    handleField: {ts_str(identity['handleField'])},")
            lines.append("  },")
        lines += ["}", ""]

    names = ", ".join(upper(p["platform"]) for p in spec["profiles"])
    lines += [
        "/** The closed launch list. */",
        f"export const LAUNCH: readonly Profile[] = [{names}]",
        "",
        "/** The launch profile for a platform name, or undefined. */",
        "export function launch(platform: string): Profile | undefined {",
        "  return LAUNCH.find((p) => p.platform === platform)",
        "}",
        "",
        "/** How many attestations a submission for this profile carries. */",
        "export function attestationCount(profile: Profile): number {",
        "  return (profile.token ? 1 : 0) + (profile.identity ? 1 : 0)",
        "}",
        "",
        "/** Governance-owned launch parameters, in seconds. */",
        f"export const MAX_FUTURE_ATTESTATION_SKEW_SECONDS = "
        f"{spec['parameters']['maxFutureAttestationSkewSeconds']}",
    ]
    for profile in spec["profiles"]:
        if "proofLifetimeSeconds" not in profile:
            continue
        lines.append(
            f"export const PROOF_LIFETIME_SECONDS_{upper(profile['platform'])} = "
            f"{profile['proofLifetimeSeconds']}"
        )
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="Write nothing; exit non-zero if a generated file is stale.",
    )
    args = parser.parse_args()

    if not SOURCE.exists():
        print(f"ERROR: {SOURCE} is missing", file=sys.stderr)
        return 1
    spec = json.loads(SOURCE.read_text(encoding="utf-8"))
    validate(spec)

    outputs = [(SOL_OUT, sol_formatted(gen_sol(spec)))]
    skipped = []
    for path, gen in ((RUST_OUT, gen_rust), (TS_OUT, gen_ts)):
        if path.parent.exists():
            outputs.append((path, gen(spec)))
        else:
            skipped.append(path)

    for path in skipped:
        print(
            f"note: skipping {path.relative_to(REPO_ROOT)} — "
            f"{path.parent.relative_to(REPO_ROOT)} does not exist yet"
        )

    if args.check:
        stale = [
            path
            for path, text in outputs
            if not path.exists() or path.read_text(encoding="utf-8") != text
        ]
        if stale:
            print(
                "ERROR: generated files are out of date. Run scripts/regen-ceremony-profiles.py",
                file=sys.stderr,
            )
            for path in stale:
                print(f"  {path.relative_to(REPO_ROOT)}", file=sys.stderr)
            return 1
        print("generated files are up to date")
        return 0

    for path, text in outputs:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
        print(f"wrote {path.relative_to(REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
