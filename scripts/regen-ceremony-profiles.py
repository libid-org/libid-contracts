def sol_doc(note: Any, indent: str = "    ") -> list[str]:
    lines = as_lines(note)
    if not lines:
        return []
    out = [f"{indent}/// @dev {lines[0]}"]
    out += [f"{indent}///      {line}" if line else f"{indent}///" for line in lines[1:]]
    return out


def gen_sol(spec: dict[str, Any]) -> str:
    profiles = spec["profiles"]
    versions = {p["ceremonyVersion"] for p in profiles}
    if len(versions) != 1:
        raise SystemExit("ERROR: the Solidity LAUNCH_VERSION assumes one version for all profiles")
    launch_version = versions.pop()

    lines = [
        "// SPDX-License-Identifier: MIT",
        "pragma solidity ^0.8.24;",
        "",
        header("//").rstrip("\n"),
        "",
        "/// @title CeremonyProfile",
        "/// @notice The tags a Platform Verifier pins, and the governance-owned",
        "///         protocol parameters it reads.",
        "///",
    ]
    lines += [f"/// {line}" if line else "///" for line in as_lines(spec.get("note"), width=70)]
    lines += [
        "library CeremonyProfile {",
        "    // --- Platform identifiers -----------------------------------------------",
        "",
    ]
    for profile in profiles:
        name = upper(profile["platform"])
        lines.append(
            f'    bytes32 internal constant PLATFORM_{name} = keccak256(bytes("{profile["platform"]}"));'
        )

    lines += [
        "",
        "    // --- Authorities --------------------------------------------------------",
        "",
        "    /// @dev The lowercase ASCII TLS server name, with no trailing dot, that the",
        "    ///      notary authenticated. It reaches the verifier as `authorityId` and",
        "    ///      never as a transcript range: the transcript holds the authority",
        "    ///      only in a prover-composed `Host` header, which says nothing about",
        "    ///      which server answered (REQ-COMMON-21, REQ-COMMON-21A).",
        "",
    ]
    for suffix, host in authorities(spec):
        lines.append(
            f'    bytes32 internal constant AUTHORITY_{suffix} = keccak256(bytes("{host}"));'
        )

    lines += [
        "",
        "    // --- Sessions -------------------------------------------------------------",
        "",
        "    /// @dev The request-line prefix each session sends, trailing space included.",
        "    ///      The space is load-bearing: without it `GET /user ` would prefix",
        "    ///      `GET /users/me`, and one profile's path would answer for another's.",
        "",
    ]
    for profile in profiles:
        name = upper(profile["platform"])
        for session_name, session in sessions_of(profile):
            const = f"{name}_{upper(session_name)}_REQUEST_LINE"
            lines.append(f'    bytes internal constant {const} = "{request_line(session)}";')

    lines += [
        "",
        "    /// @dev The token request's head, byte for byte, ending at the",
        "    ///      `content-length` value the verifier reads out of the transcript.",
        "    ///      Its headers are revealed, so leaving them uncompared left the one",
        "    ///      that decides how the platform parses the body -- the media type",
        "    ///      REQ-COMMON-21B fixes -- public and unconstrained.",
        "    ///",
        "    ///      Pinned as ONE run rather than as a set of lines: the head is fixed",
        "    ///      bytes, so a comparison against it needs no header parser, and a",
        "    ///      parser is where an added, reordered or restated header would have",
        "    ///      to be caught one rule at a time.",
        "",
    ]
    for profile in profiles:
        token = profile["sessions"].get("token")
        if token is None:
            continue
        const = f"{upper(profile['platform'])}_TOKEN_REQUEST_HEADERS"
        lines.append(
            f'    bytes internal constant {const} = "{escaped(request_header_block(token))}";'
        )

    lines += [
        "",
        "    /// @dev How many committed ranges the token request carries. A confidential",
        "    ///      client commits its secret and a public client hides nothing, so this",
        "    ///      is one or zero and never a preference.",
        "",
    ]
    for profile in profiles:
        token = profile["sessions"].get("token")
        if token is None:
            continue
        count = 0 if token["secretField"] is None else 1
        lines.append(
            f"    uint256 internal constant {upper(profile['platform'])}_TOKEN_SENT_COMMITMENTS = {count};"
        )

    lines += [
        "",
        "    /// @dev The two identity members a Platform Verifier reads out of the",
        "    ///      revealed response bytes (REQ-PLAT-51).",
        "",
    ]
    for profile in profiles:
        identity = profile["sessions"].get("identity")
        if identity is None:
            continue
        name = upper(profile["platform"])
        lines.append(f'    string internal constant {name}_ID_FIELD = "{identity["idField"]}";')
        lines.append(
            f'    string internal constant {name}_HANDLE_FIELD = "{identity["handleField"]}";'
        )

    lines += [
        "",
        "    // --- Launch profile shape ------------------------------------------------",
        "",
        "    /// @dev Launch profiles are "
        + ", ".join(f"`{p['platform']}/v{p['ceremonyVersion']}`" for p in profiles)
        + "",
        "    ///      (REQ-PLAT-01).",
        f"    uint16 internal constant LAUNCH_VERSION = {launch_version};",
        "",
        "    /// @dev Derived from the session list each profile fixes, never stated",
        "    ///      beside it (REQ-COMMON-41).",
        "    function attestationCount(bytes32 platformId) internal pure returns (uint8) {",
    ]
    by_count: dict[int, list[str]] = {}
    for profile in profiles:
        by_count.setdefault(len(sessions_of(profile)), []).append(upper(profile["platform"]))
    for count in sorted(by_count):
        test = " || ".join(f"platformId == PLATFORM_{name}" for name in by_count[count])
        lines.append(f"        if ({test}) return {count};")
    lines += [
        "        revert UnknownPlatform(platformId);",
        "    }",
        "",
        "    error UnknownPlatform(bytes32 platformId);",
        "",
        "    // --- Protocol parameters -------------------------------------------------",
        "",
    ]
    lines += sol_doc(spec["parameters"].get("note"))
    for profile in profiles:
        if "proofLifetimeSeconds" not in profile:
            continue
        lines.append(
            f"    uint64 internal constant LAUNCH_PROOF_LIFETIME_{upper(profile['platform'])} = "
            f"{profile['proofLifetimeSeconds']};"
        )
    lines.append(
        "    uint64 internal constant LAUNCH_MAX_FUTURE_ATTESTATION_SKEW = "
        f"{spec['parameters']['maxFutureAttestationSkewSeconds']};"
    )
    lines += ["}", ""]
    return "\n".join(lines)


def sol_formatted(source: str) -> str:
    """Run the repository's `forge fmt` over generated Solidity."""
    if shutil.which("forge") is None:
        print("ERROR: forge is required to format the generated Solidity", file=sys.stderr)
        raise SystemExit(1)
    done = subprocess.run(
        ["forge", "fmt", "--raw", "-"],
        input=source,
        capture_output=True,
        text=True,
        cwd=SOLIDITY_ROOT,
    )
    if done.returncode != 0:
        print(f"ERROR: forge fmt failed:\n{done.stderr}", file=sys.stderr)
        raise SystemExit(1)
    return done.stdout


